import { describe, expect, it } from "vitest";
import { posterHeadline } from "./poster-headline";

describe("기본 포스터 작품명", () => {
  it.each([
    ["블랙코미디 연극 <죽여주는 이야기> 2026년 4차 배우 모집 (~10.28)", "죽여주는 이야기"],
    ["2027 창작 음악극 《한 사람》 캐스팅 오디션", "한 사람"],
    ["가족뮤지컬 \"눈의여왕\" 배우 오디션 공고", "눈의여왕"],
    ["###어린왕자와 산타의 결합 <어린산타> 전 배역모집######3", "어린산타"],
    ["<쉿!> 전배역 오디션", "쉿!"],
    ["창작극 [사로] 배우모집 (수정)", "사로"],
    ["[긴급모집] '면천읍성 360도 런' 행사 여성 배우 1명 모집 (11/7~11/8)", "면천읍성 360도 런"],
  ])("%s에서 작품명을 꺼낸다", (title, expected) => {
    expect(posterHeadline(title)).toBe(expected);
  });

  it("장르 이름만 든 꺾쇠와 작은따옴표 안의 단체명은 작품명으로 쓰지 않는다", () => {
    expect(posterHeadline("<뮤지컬>더멜로디 전배역 모집합니다")).toBe("뮤지컬 더멜로디 전배역 모집");
    expect(posterHeadline("‘극단아리’ 크리스마스 공연 배우 모집")).toBe("‘극단아리’ 크리스마스 공연 배우 모집");
  });

  it.each([
    ["총페이 1,200,000원 여성댄스팀 공연멤버 모집(총 7회 공연)", "여성댄스팀 공연멤버 모집"],
    ["(급)12인의 성난 사람들 _3번배역", "12인의 성난 사람들"],
    ["[급구] 가족뮤지컬 출연 배우 모집", "가족뮤지컬 출연 배우 모집"],
    ["10/31 뮤지컬 갈라쇼/ 여자배우2명 (연습1회,행사10분)", "뮤지컬 갈라쇼"],
    ["10월 21일 전통 공연 오프닝 퍼포머 모집합니다.", "전통 공연 오프닝 퍼포머 모집"],
  ])("작품명이 없으면 날짜·금액·괄호를 걷어낸다: %s", (title, expected) => {
    expect(posterHeadline(title)).toBe(expected);
  });

  it("제목 전체가 대괄호여도 빈 문구를 만들지 않는다", () => {
    expect(posterHeadline("[★ 메가메타 -신인배우 오디션 ★]")).toBe("메가메타 -신인배우 오디션");
  });
});
