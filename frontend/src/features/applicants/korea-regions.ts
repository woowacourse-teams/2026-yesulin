export const sigunguOptions = (sido: string): readonly string[] =>
  KOREA_REGIONS.find((region) => region.sido === sido)?.sigungu ?? [];

export function formatKoreaRegion(region: KoreaRegion): string {
  return [region.sido, region.sigungu].filter(Boolean).join(" ");
}

/** 저장된 문자열에서 시·도와 시·군·구를 읽는다. 알아볼 수 없으면 빈 값을 돌려준다. */
export function parseKoreaRegion(value: string): KoreaRegion {
  const text = value.trim();
  if (!text) return { sido: "", sigungu: "" };
  const [head = "", ...rest] = text.split(/\s+/);
  const sido = KOREA_REGIONS.some((region) => region.sido === head) ? head : SIDO_ALIASES[head] ?? "";
  if (!sido) return { sido: "", sigungu: "" };
  const options = sigunguOptions(sido);
  const sigungu = options.find((option) => rest[0] === option) ?? "";
  return { sido, sigungu };
}

/** 시·도만 고른 상태는 아직 지역을 정하지 않은 것으로 본다. 하위 구역이 없는 세종은 예외다. */
export function isCompleteKoreaRegion(value: string): boolean {
  const region = parseKoreaRegion(value);
  if (!region.sido) return false;
  return sigunguOptions(region.sido).length === 0 || Boolean(region.sigungu);
}
