package art.yesulin.auditionpost.domain;

/**
 * 공고의 공개 상태. 가져오거나 운영자가 쓴 공고는 검토 전으로 시작해 운영자가 공개하고, 제작사 요청이나 문제가 있으면 내린다.
 * 기획사가 올린 공고는 바로 공개한다. 검토 전과 내린 공고는 공개 목록에서 빠지고, 상세 주소는 원문이 있으면 원문으로 보내고
 * 없으면 없는 공고처럼 404다.
 */
public enum AuditionPostStatus {

    /** 가져오거나 운영자가 쓴 뒤 아직 공개하지 않은 공고. 공개 상태를 다시 검토 전으로 돌리지는 않는다. */
    PENDING,
    PUBLISHED,
    /** 공개했다가 내린 공고. */
    HIDDEN
}
